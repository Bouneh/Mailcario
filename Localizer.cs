    public static string T(string key) => Words.TryGetValue(key, out var value)
        ? (Language == "fr" ? value.Fr : value.En) : key;

    public static void SetLanguage(string language)
    {
        if (language is not ("fr" or "en") || language == Language) return;
        Language = language;
        CultureInfo.CurrentCulture = CultureInfo.GetCultureInfo(language);
        Changed?.Invoke();
    }
